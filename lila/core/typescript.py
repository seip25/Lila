"""TypeScript interfaces from Pydantic schemas and Lila models.

``lila react types`` imports every module under ``app/`` and writes
``resources/react/types/lila.ts`` with one ``export interface`` per Pydantic
model and per ``BaseModel`` table (columns, ``__private_fields__`` excluded),
so React pages can type the props sent by ``react_render``::

    import type { User, LoginModel } from "@/types/lila";
"""

from __future__ import annotations

import importlib
import inspect
import json
import os
import re
import sys
from typing import Any, Dict, Iterable, List, Optional, Tuple

HEADER = "// Generated by `lila react types` — do not edit; run the command again after changing models.\n"
_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _key(name: str) -> str:
    return name if _IDENT.match(name) else json.dumps(name)


def _literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False) if not isinstance(value, bool) else ("true" if value else "false")


class _SchemaConverter:
    def __init__(self, defs: Dict[str, Any], names: Dict[str, str]):
        self.defs = defs
        self.names = names  # $defs name -> exported interface name

    def ts(self, schema: Any, indent: str = "") -> str:
        if not isinstance(schema, dict) or not schema:
            return "unknown"
        if "$ref" in schema:
            ref = schema["$ref"].split("/")[-1]
            return self.names.get(ref, ref)
        if "const" in schema:
            return _literal(schema["const"])
        if "enum" in schema:
            return " | ".join(_literal(v) for v in schema["enum"]) or "never"
        for combo in ("anyOf", "oneOf"):
            if combo in schema:
                parts = list(dict.fromkeys(self.ts(item, indent) for item in schema[combo]))
                return " | ".join(parts)
        if "allOf" in schema:
            return " & ".join(self.ts(item, indent) for item in schema["allOf"])
        kind = schema.get("type")
        if isinstance(kind, list):
            return " | ".join(self.ts({**schema, "type": k}, indent) for k in kind)
        if kind == "string":
            return "string"
        if kind in ("integer", "number"):
            return "number"
        if kind == "boolean":
            return "boolean"
        if kind == "null":
            return "null"
        if kind == "array":
            if "prefixItems" in schema:
                return "[" + ", ".join(self.ts(item, indent) for item in schema["prefixItems"]) + "]"
            inner = self.ts(schema.get("items", {}), indent)
            return f"({inner})[]" if "|" in inner or "&" in inner else f"{inner}[]"
        if kind == "object" or "properties" in schema:
            if "properties" in schema:
                return self.object_body(schema, indent)
            extra = schema.get("additionalProperties")
            value = self.ts(extra, indent) if isinstance(extra, dict) else "unknown"
            return f"Record<string, {value}>"
        return "unknown"

    def object_body(self, schema: Dict[str, Any], indent: str = "") -> str:
        required = set(schema.get("required", []))
        lines = ["{"]
        for name, prop in (schema.get("properties") or {}).items():
            optional = "" if name in required else "?"
            doc = prop.get("description") if isinstance(prop, dict) else None
            if doc:
                lines.append(f"{indent}  /** {str(doc).replace('*/', '* /')} */")
            lines.append(f"{indent}  {_key(name)}{optional}: {self.ts(prop, indent + '  ')};")
        lines.append(f"{indent}}}")
        return "\n".join(lines)


def _column_ts(column: Any) -> str:
    try:
        python_type = column.type.python_type
    except Exception:
        python_type = None
    name = type(column.type).__name__.lower()
    if python_type is bool or "bool" in name:
        ts = "boolean"
    elif python_type in (int, float) or any(k in name for k in ("int", "float", "numeric", "decimal", "real", "double")):
        ts = "number"
    elif "json" in name:
        ts = "unknown"
    elif python_type in (dict, list):
        ts = "unknown"
    else:
        ts = "string"  # str, dates/times (ISO strings in JSON), uuid, enum values...
    nullable = getattr(column, "nullable", True) and not getattr(column, "primary_key", False)
    return f"{ts} | null" if nullable and ts != "unknown" else ts


def _is_pydantic(obj: Any) -> bool:
    try:
        from pydantic import BaseModel as PydanticBaseModel

        return inspect.isclass(obj) and issubclass(obj, PydanticBaseModel) and obj is not PydanticBaseModel
    except Exception:
        return False


def _is_table_model(obj: Any) -> bool:
    return inspect.isclass(obj) and hasattr(obj, "__table__") and hasattr(obj.__table__, "columns")


def table_interface(model: Any, name: Optional[str] = None) -> str:
    private = set(getattr(model, "__private_fields__", ()) or ())
    lines = [f"export interface {name or model.__name__} {{"]
    for column in model.__table__.columns:
        if column.name in private:
            continue
        lines.append(f"  {_key(column.name)}: {_column_ts(column)};")
    lines.append("}")
    return "\n".join(lines)


def pydantic_interfaces(models: Iterable[Tuple[str, Any]]) -> List[str]:
    """One interface per model plus its nested ``$defs`` (deduplicated)."""
    blocks: Dict[str, str] = {}
    exported = {name for name, _ in models}
    for name, model in models:
        try:
            schema = model.model_json_schema(mode="serialization", ref_template="#/$defs/{model}")
        except Exception:
            blocks[name] = f"export type {name} = Record<string, unknown>; // schema not serializable"
            continue
        defs = dict(schema.pop("$defs", {}) or {})
        names = {key: key for key in defs}
        converter = _SchemaConverter(defs, names)
        for def_name, def_schema in defs.items():
            if def_name in blocks or (def_name in exported and def_name != name):
                continue
            if "properties" in def_schema:
                blocks[def_name] = f"export interface {def_name} {converter.object_body(def_schema)}"
            else:
                blocks[def_name] = f"export type {def_name} = {converter.ts(def_schema)};"
        if "properties" in schema:
            blocks[name] = f"export interface {name} {converter.object_body(schema)}"
        else:
            blocks[name] = f"export type {name} = {converter.ts(schema)};"
    return list(blocks.values())


def discover(package: str = "app") -> Tuple[List[Tuple[str, Any]], List[Tuple[str, Any]], List[str]]:
    """Imports ``package`` recursively; returns (pydantic, tables, import errors)."""
    if os.getcwd() not in sys.path:
        sys.path.insert(0, os.getcwd())
    errors: List[str] = []
    modules = []
    try:
        root = importlib.import_module(package)
    except Exception as exc:
        return [], [], [f"{package}: {exc}"]
    modules.append(root)
    # Walk the files: app/models, app/routes... are often folders without
    # __init__.py (namespace packages), which pkgutil does not list.
    names = []
    for base in list(getattr(root, "__path__", [])):
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [d for d in dirnames if not d.startswith((".", "__")) and d not in ("data", "cache", "logs", "locales")]
            rel = os.path.relpath(dirpath, base)
            prefix = package if rel == "." else f"{package}." + rel.replace(os.sep, ".")
            for filename in sorted(filenames):
                if filename.endswith(".py") and filename != "__init__.py":
                    names.append(f"{prefix}.{filename[:-3]}")
    for name in names:
        try:
            modules.append(importlib.import_module(name))
        except Exception as exc:  # a broken module should not stop the others
            errors.append(f"{name}: {exc}")

    pydantic: Dict[str, Any] = {}
    tables: Dict[str, Any] = {}
    for module in modules:
        for _attr, obj in vars(module).items():
            if not inspect.isclass(obj) or not str(getattr(obj, "__module__", "")).startswith(f"{package}."):
                continue
            target = tables if _is_table_model(obj) else pydantic if _is_pydantic(obj) else None
            if target is None:
                continue
            name = obj.__name__
            if name in target and target[name] is not obj:
                name = obj.__module__.split(".")[-1].title().replace("_", "") + name
            target[name] = obj
    return sorted(pydantic.items()), sorted(tables.items()), errors


def generate(package: str = "app") -> Tuple[str, Dict[str, int], List[str]]:
    pydantic, tables, errors = discover(package)
    blocks = [table_interface(model, name) for name, model in tables]
    table_names = {name for name, _ in tables}
    blocks += pydantic_interfaces([(n, m) for n, m in pydantic if n not in table_names])
    content = HEADER + "\n" + "\n\n".join(blocks) + ("\n" if blocks else "export {};\n")
    return content, {"tables": len(tables), "schemas": len(pydantic)}, errors


def write(path: str = os.path.join("resources", "react", "types", "lila.ts"), package: str = "app"):
    content, counts, errors = generate(package)
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    changed = True
    if os.path.isfile(path):
        with open(path, "r", encoding="utf-8") as fh:
            changed = fh.read() != content
    if changed:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
    return path, counts, errors, changed
