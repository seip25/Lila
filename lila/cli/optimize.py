import sys
import os
import json
import re
from pathlib import Path

if os.getcwd() not in sys.path:
    sys.path.insert(0, os.getcwd())

try:
    import rjsmin
except ImportError:
    rjsmin = None

try:
    import rcssmin
except ImportError:
    rcssmin = None

try:
    from PIL import Image
except ImportError:
    Image = None

project_root = os.getcwd()

def process_js(file_path: str, new_file_path: str) -> bool:
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()
        if rjsmin:
            minified = rjsmin.jsmin(content)
        else:
            # Safe comment removal that preserves URLs ('wss://', 'https://') and strings
            minified = re.sub(r'/\*[\s\S]*?\*/', '', content)
            minified = re.sub(r'^\s*//.*$', '', minified, flags=re.MULTILINE)
            minified = re.sub(r'\n\s*\n+', '\n', minified).strip()
        with open(new_file_path, 'w', encoding='utf-8') as f:
            f.write(minified)
        return True
    except Exception as e:
        print(f"  ⚠️ Error minifying JS {file_path}: {e}")
        return False

def process_css(file_path: str, new_file_path: str) -> bool:
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()
        if rcssmin:
            minified = rcssmin.cssmin(content)
        else:
            minified = re.sub(r'/\*.*?\*/', '', content, flags=re.DOTALL)
            minified = re.sub(r'\s+', ' ', minified)
        with open(new_file_path, 'w', encoding='utf-8') as f:
            f.write(minified)
        return True
    except Exception as e:
        print(f"  ⚠️ Error minifying CSS {file_path}: {e}")
        return False

def process_image(file_path: str, new_file_path: str) -> bool:
    if not Image:
        return False
    try:
        if os.path.exists(new_file_path) and os.path.getmtime(new_file_path) > os.path.getmtime(file_path):
            return True
        with Image.open(file_path) as img:
            if img.mode == 'P':
                img = img.convert('RGBA')
            img.save(new_file_path, 'webp', quality=82, method=4)
        return True
    except Exception as e:
        print(f"  ⚠️ Error optimizing Image {file_path}: {e}")
        return False

def main():
    print("⚡ Lila Optimize: Minifying static assets and converting images to WebP...")
    public_folder = os.path.join(project_root, "public")
    app_folder = os.path.join(project_root, "app")
    cache_folder = os.path.join(app_folder, "cache")
    manifest_path = os.path.join(cache_folder, "assets_manifest.json")
    manifest_py_path = os.path.join(cache_folder, "manifest_cache.py")

    if not os.path.exists(public_folder):
        print("❌ Error: 'public' folder not found in current directory.")
        return

    os.makedirs(cache_folder, exist_ok=True)
    manifest = {}

    for root, _, files in os.walk(public_folder):
        for file in files:
            file_path = os.path.join(root, file)
            relative_path = os.path.relpath(file_path, public_folder).replace("\\", "/")

            if file.endswith('.js') and not file.endswith('.min.js'):
                new_relative_path = relative_path[:-3] + ".min.js"
                new_file_path = os.path.join(public_folder, new_relative_path)
                if process_js(file_path, new_file_path):
                    manifest[relative_path] = new_relative_path

            elif file.endswith('.css') and not file.endswith('.min.css'):
                new_relative_path = relative_path[:-4] + ".min.css"
                new_file_path = os.path.join(public_folder, new_relative_path)
                if process_css(file_path, new_file_path):
                    manifest[relative_path] = new_relative_path

            elif file.lower().endswith(('.png', '.jpg', '.jpeg')) and Image:
                file_ext = os.path.splitext(file)[1]
                new_relative_path = relative_path[:-len(file_ext)] + ".webp"
                new_file_path = os.path.join(public_folder, new_relative_path)
                if process_image(file_path, new_file_path):
                    manifest[relative_path] = new_relative_path

    with open(manifest_py_path, 'w', encoding='utf-8') as f:
        f.write("# Auto-generated by lila-optimize — DO NOT EDIT DIRECTLY\n")
        f.write(f"ASSET_MANIFEST = {repr(manifest)}\n")

    with open(manifest_path, 'w', encoding='utf-8') as f:
        json.dump(manifest, f, indent=2)

    print(f"✅ Optimized {len(manifest)} assets. Manifest written to app/cache/manifest_cache.py")

if __name__ == "__main__":
    main()
