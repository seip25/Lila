import os
import sys
import stat
from urllib.parse import urlparse
import typer
from typing import Optional

app = typer.Typer(help="Lila Deploy CLI — Generate production deployment configurations for Linux (systemd, Nginx) and Windows Server.")


def _safe_token(value: Optional[str], fallback: str, allowed: str = "-_.@") -> str:
    cleaned = "".join(ch for ch in str(value or "") if ch.isalnum() or ch in allowed).strip("-_.@")
    return cleaned or fallback


def _safe_domain(value: Optional[str]) -> str:
    cleaned = "".join(ch for ch in str(value or "") if ch.isalnum() or ch in ".-").strip(".-")
    return cleaned or "localhost"

def generate_deploy_files(
    output_dir: str = "deploy",
    domain: Optional[str] = None,
    port: Optional[int] = None,
    user: Optional[str] = None,
    group: Optional[str] = None,
    workers: Optional[int] = None,
    service_name: Optional[str] = None,
    with_worker: bool = False,
    project_dir: Optional[str] = None,
    extra_server_names: Optional[list] = None,
) -> dict:
    """Generates production deployment files in output_dir and returns metadata."""
    from lila.core.config import ConfigLoader, ENV_CONFIG, get_secret_key, _is_placeholder_secret

    ConfigLoader.load()
    root_dir = os.path.abspath(project_dir or os.getcwd())

    # 1. Resolve domain
    if not domain:
        app_url = str(ENV_CONFIG.get("APP_URL", "") or "").strip()
        if app_url:
            parsed = urlparse(app_url if "://" in app_url else f"http://{app_url}")
            domain = parsed.netloc.split(":")[0] if parsed.netloc else "localhost"
        else:
            domain = "localhost"
    domain = _safe_domain(domain)
    server_names = " ".join(
        dict.fromkeys([domain] + [_safe_domain(name) for name in (extra_server_names or []) if name])
    )

    # 2. Resolve port
    if port is None:
        try:
            port = int(ENV_CONFIG.get("PORT", 3002) or 3002)
        except (ValueError, TypeError):
            port = 3002

    # 3. Resolve user & group
    run_user = _safe_token(user or os.getenv("USER") or "www-data", "www-data")
    run_group = _safe_token(group or run_user, run_user)

    # 4. Resolve workers
    if workers is None:
        cache_driver = str(ENV_CONFIG.get("CACHE_DRIVER", "memory")).lower()
        workers = 2 if cache_driver == "redis" else 1

    # 5. Resolve service name (.env SERVICE_NAME, then folder name)
    if not service_name:
        service_name = str(ENV_CONFIG.get("SERVICE_NAME", "") or "").strip() or None
    if not service_name:
        folder_name = os.path.basename(root_dir).lower()
        clean_name = "".join(c if c.isalnum() or c in ("-", "_") else "-" for c in folder_name).strip("-")
        service_name = clean_name or "lila-app"
    service_name = _safe_token(service_name, "lila-app")

    # 6. Check virtualenv path
    venv_bin = "/usr/local/bin"
    for candidate in (".venv", "venv"):
        cand_bin = os.path.join(root_dir, candidate, "bin")
        if os.path.isdir(cand_bin):
            venv_bin = cand_bin
            break

    os.makedirs(output_dir, exist_ok=True)

    # File 1: start_lila.sh
    sh_content = f"""#!/usr/bin/env bash
# Auto-generated by Lila Framework v2.0.0 Deploy CLI
set -e

PROJECT_DIR="{root_dir.replace('"', '\\"')}"
cd "$PROJECT_DIR"

if [ -f "$PROJECT_DIR/.venv/bin/activate" ]; then
    source "$PROJECT_DIR/.venv/bin/activate"
elif [ -f "$PROJECT_DIR/venv/bin/activate" ]; then
    source "$PROJECT_DIR/venv/bin/activate"
fi

exec lila run --host 127.0.0.1 --port {port} -w {workers} --proxy-headers
"""
    sh_path = os.path.join(output_dir, "start_lila.sh")
    with open(sh_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(sh_content)
    try:
        current_stat = os.stat(sh_path)
        os.chmod(sh_path, current_stat.st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except Exception:
        pass

    # File 2: <service_name>.service
    systemd_content = f"""[Unit]
Description=Lila Framework Application ({service_name})
After=network.target

[Service]
Type=simple
User={run_user}
Group={run_group}
WorkingDirectory={root_dir}
Environment="PATH={venv_bin}:/usr/local/bin:/usr/bin:/bin"
Environment="APP_ENV=production"
ExecStart="{os.path.join(root_dir, output_dir, "start_lila.sh").replace('\\\\', '/')}"
Restart=always
RestartSec=3
LimitNOFILE=65535

[Install]
WantedBy=multi-user.target
"""
    service_filename = f"{service_name}.service"
    service_path = os.path.join(output_dir, service_filename)
    with open(service_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(systemd_content)

    # File 3 (optional): <service_name>-worker.service
    worker_service_path = None
    if with_worker:
        worker_content = f"""[Unit]
Description=Lila Framework Background Worker ({service_name})
After=network.target

[Service]
Type=simple
User={run_user}
Group={run_group}
WorkingDirectory={root_dir}
Environment="PATH={venv_bin}:/usr/local/bin:/usr/bin:/bin"
Environment="APP_ENV=production"
ExecStart={venv_bin}/lila worker
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
"""
        worker_filename = f"{service_name}-worker.service"
        worker_service_path = os.path.join(output_dir, worker_filename)
        with open(worker_service_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(worker_content)

    # File 4: <domain>.nginx.conf
    # Static assets are served by Lila at /public, /js, /img, /swagger and
    # /uploads. Serve them directly from Nginx and keep the ASGI app for HTML,
    # API and WebSocket traffic.
    static_root = root_dir.replace('\\\\', '/')
    nginx_content = f"""# Nginx configuration for {domain}
# Auto-generated by Lila Framework v2.0.0 Deploy CLI

map $http_upgrade $connection_upgrade {{
    default upgrade;
    '' close;
}}

server {{
    listen 80;
    server_name {server_names};

    client_max_body_size 50M;

    # Lila always serves its own client scripts from the installed package
    # (so `pip install -U lila-framework` updates them): proxy, don't alias.
    location = /js/lila-client.js {{
        proxy_pass http://127.0.0.1:{port};
        proxy_set_header Host $host;
    }}

    location = /js/ws.js {{
        proxy_pass http://127.0.0.1:{port};
        proxy_set_header Host $host;
    }}

    # Bundled/static assets (Lila mounts these paths directly).
    location ^~ /public/ {{
        alias "{static_root}/public/";
        gzip_static on;
        expires 30d;
        add_header Cache-Control "public, no-transform";
    }}

    location ^~ /js/ {{
        alias "{static_root}/public/js/";
        gzip_static on;
        expires 30d;
        add_header Cache-Control "public, no-transform";
    }}

    location ^~ /img/ {{
        alias "{static_root}/public/img/";
        gzip_static on;
        expires 30d;
        add_header Cache-Control "public, no-transform";
    }}

    location ^~ /swagger/ {{
        alias "{static_root}/public/swagger/";
        gzip_static on;
        expires 30d;
        add_header Cache-Control "public, no-transform";
    }}

    location ^~ /uploads/ {{
        alias "{static_root}/public/uploads/";
        expires 7d;
        add_header Cache-Control "public, no-transform";
    }}

    # Reverse proxy to Lila ASGI application
    location / {{
        proxy_pass http://127.0.0.1:{port};
        proxy_http_version 1.1;

        # WebSocket support
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;

        # Standard proxy headers
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Forwarded-Host $host;
        proxy_set_header X-Forwarded-Port $server_port;

        # Timeouts
        proxy_connect_timeout 60s;
        proxy_send_timeout 60s;
        proxy_read_timeout 60s;
    }}
}}
"""
    nginx_filename = f"{domain}.nginx.conf"
    nginx_path = os.path.join(output_dir, nginx_filename)
    with open(nginx_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(nginx_content)

    # File 5: start_lila.ps1 (Windows Server / Task Scheduler)
    ps1_content = f"""# Lila Framework Windows Server Startup Script
# Auto-generated by Lila Framework v2.0.0 Deploy CLI
$ErrorActionPreference = "Stop"

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$ProjectDir = Split-Path -Parent $ScriptDir
Set-Location $ProjectDir

if (Test-Path "$ProjectDir\\.venv\\Scripts\\Activate.ps1") {{
    & "$ProjectDir\\.venv\\Scripts\\Activate.ps1"
}} elseif (Test-Path "$ProjectDir\\venv\\Scripts\\Activate.ps1") {{
    & "$ProjectDir\\venv\\Scripts\\Activate.ps1"
}}

Write-Host "🚀 Starting Lila on port {port} with {workers} worker(s)..." -ForegroundColor Cyan
lila run --host 127.0.0.1 --port {port} -w {workers} --proxy-headers
"""
    ps1_path = os.path.join(output_dir, "start_lila.ps1")
    with open(ps1_path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(ps1_content)

    return {
        "domain": domain,
        "port": port,
        "user": run_user,
        "group": run_group,
        "workers": workers,
        "service_name": service_name,
        "service_path": service_path,
        "worker_service_path": worker_service_path,
        "nginx_path": nginx_path,
        "sh_path": sh_path,
        "ps1_path": ps1_path,
    }


@app.callback(invoke_without_command=True)
def deploy(
    ctx: typer.Context,
    domain: Optional[str] = typer.Option(None, "--domain", "-d", help="Site domain (e.g. example.com)"),
    port: Optional[int] = typer.Option(None, "--port", "-p", help="Internal listen port (default: from .env or 3002)"),
    user: Optional[str] = typer.Option(None, "--user", "-u", help="Linux service user (default: current or www-data)"),
    group: Optional[str] = typer.Option(None, "--group", "-g", help="Linux service group (default: same as user)"),
    workers: Optional[int] = typer.Option(None, "--workers", "-w", help="Number of workers (default: 1 for SQLite, 2+ for Redis)"),
    service_name: Optional[str] = typer.Option(None, "--service-name", "-s", help="Systemd service name (default: folder name)"),
    with_worker: bool = typer.Option(False, "--with-worker", help="Also generate background worker systemd unit"),
    output_dir: str = typer.Option("deploy", "--out-dir", "-o", help="Output directory for generated files"),
):
    """
    Generates production deployment files for Linux (systemd, Nginx) and Windows Server.

    For a guided install on a Linux server run: sudo lila deploy setup
    """
    if ctx.invoked_subcommand is not None:
        return
    from lila.core.config import ConfigLoader, ENV_CONFIG, get_secret_key, _is_placeholder_secret

    ConfigLoader.load()

    # Warn if DEBUG is enabled or SECRET_KEY is weak
    warnings = []
    if ENV_CONFIG.get_bool("DEBUG", False):
        warnings.append("⚠️  DEBUG=True in .env! Make sure to set DEBUG=False for production.")
    secret = get_secret_key()
    if not secret or _is_placeholder_secret(secret) or len(secret) < 32:
        warnings.append("⚠️  SECRET_KEY is empty, short or placeholder! Run 'lila secret-key' before deploying.")

    if warnings:
        typer.secho("\n--- Configuration Warnings ---", fg=typer.colors.YELLOW, bold=True)
        for w in warnings:
            typer.secho(w, fg=typer.colors.YELLOW)
        typer.echo("")

    cache_driver = str(ENV_CONFIG.get("CACHE_DRIVER", "memory")).lower()
    if with_worker and cache_driver != "redis":
        typer.secho(
            "ℹ️  The worker unit will consume the SQLite task queue (app/data/lila_tasks.db); "
            "set TASKS_IN_PROCESS=false in .env so web workers leave the queue to it.",
            fg=typer.colors.CYAN,
        )
    if workers and workers > 1 and cache_driver != "redis":
        typer.secho(
            "⚠️  Multiple workers with the memory cache: sessions/rate limits are per process.",
            fg=typer.colors.YELLOW,
        )

    info = generate_deploy_files(
        output_dir=output_dir,
        domain=domain,
        port=port,
        user=user,
        group=group,
        workers=workers,
        service_name=service_name,
        with_worker=with_worker,
    )

    typer.secho(f"✅ Production deployment files generated in '{output_dir}/':", fg=typer.colors.GREEN, bold=True)
    typer.echo(f"  • Bash starter:    {info['sh_path']}")
    typer.echo(f"  • Systemd service: {info['service_path']}")
    if info.get("worker_service_path"):
        typer.echo(f"  • Worker service:  {info['worker_service_path']}")
    typer.echo(f"  • Nginx config:    {info['nginx_path']}")
    typer.echo(f"  • PowerShell:      {info['ps1_path']}")

    srv = info["service_name"]
    dom = info["domain"]
    nginx_file = f"{dom}.nginx.conf"

    typer.secho("\n📋 Step-by-Step Production Deployment Guide (Ubuntu/Debian):", fg=typer.colors.CYAN, bold=True)
    typer.echo(f"  1. Copy systemd service unit:")
    typer.secho(f"     sudo cp {output_dir}/{srv}.service /etc/systemd/system/", fg=typer.colors.WHITE, bold=True)
    if info.get("worker_service_path"):
        typer.secho(f"     sudo cp {output_dir}/{srv}-worker.service /etc/systemd/system/", fg=typer.colors.WHITE, bold=True)
    typer.echo(f"\n  2. Enable and start application service:")
    typer.secho(f"     sudo systemctl daemon-reload && sudo systemctl enable --now {srv}", fg=typer.colors.WHITE, bold=True)
    if info.get("worker_service_path"):
        typer.secho(f"     sudo systemctl enable --now {srv}-worker", fg=typer.colors.WHITE, bold=True)
    typer.echo(f"\n  3. Configure Nginx reverse proxy:")
    typer.secho(f"     sudo cp {output_dir}/{nginx_file} /etc/nginx/sites-available/", fg=typer.colors.WHITE, bold=True)
    typer.secho(f"     sudo ln -s /etc/nginx/sites-available/{nginx_file} /etc/nginx/sites-enabled/", fg=typer.colors.WHITE, bold=True)
    typer.secho(f"     sudo nginx -t && sudo systemctl reload nginx", fg=typer.colors.WHITE, bold=True)
    typer.echo(f"\n  4. Obtain free SSL certificate with Let's Encrypt (Certbot):")
    typer.secho(f"     sudo certbot --nginx -d {dom}\n", fg=typer.colors.GREEN, bold=True)


@app.command("setup")
def setup(
    yes: bool = typer.Option(False, "--yes", "-y", help="Accept every default answer (non-interactive)."),
    dry_run: bool = typer.Option(False, "--dry-run", help="Only print the commands, install nothing."),
    project_dir: str = typer.Option(".", "--project-dir", help="Project root (where .env lives)."),
):
    """
    Interactive Linux production setup (run with sudo): fixes .env (DEBUG,
    HOST, SECRET_KEY, APP_URL), installs the systemd service, the Nginx site
    and an HTTPS certificate with Certbot, asking before each change.
    """
    from lila.cli.deploy_setup import run_setup

    run_setup(project_dir, assume_yes=yes, dry_run=dry_run)


if __name__ == "__main__":
    app()
